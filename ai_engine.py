SEASONAL_TIPS = {
    "summer": "☀️ 여름철 추가 팁: 외출 시 에어컨 완전히 끄기, 귀가 30분 전 예약으로 과냉방 방지",
    "winter": "❄️ 겨울철 추가 팁: 전기장판 보다 두꺼운 이불 활용, 내복 착용으로 난방 온도 2°C 낮추기",
    "normal": "🌤️ 환절기 팁: 자연환기 적극 활용, 냉난방 없이 지낼 수 있는 좋은 시기예요",
}


def _get_season(month: int) -> str:
    if month in [6, 7, 8, 9]:
        return "summer"
    elif month in [11, 12, 1, 2, 3]:
        return "winter"
    return "normal"


def get_ai_advice(usage: int, month: int, total_bill: int, tiers: list) -> str:
    """
    누진 구간과 계절에 맞는 절약 조언 반환.
    (API 없이 동작하는 고정 텍스트 버전)
    """
    # 현재 구간 파악
    current_tier = 1
    for t in tiers:
        if t["used"] > 0:
            current_tier = t["tier"]

    data = TIPS[current_tier]
    season_tip = SEASONAL_TIPS[_get_season(month)]

    # 텍스트 조합
    lines = []
    lines.append(f"{data['title']}\n")
    lines.append(f"{data['summary']}\n")

    for i, (title, desc) in enumerate(data["tips"], 1):
        lines.append(f"{i}. {title}\n   {desc}\n")

    lines.append(f"\n{season_tip}")

    # 요금 절약 시뮬레이션
    if current_tier >= 2:
        save_kwh = min(usage - 200, 100)
        if save_kwh > 0:
            lines.append(f"\n\n💰 만약 {save_kwh}kWh를 줄인다면?\n   현재 {total_bill:,}원 → 약 {total_bill - save_kwh*200:,}원 예상 (약 {save_kwh*200:,}원 절약)")

    return "\n".join(lines)
